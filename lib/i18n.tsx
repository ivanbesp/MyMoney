const DICTS: Record<Lang, Record<string, string>> = { ru, en };

function interpolate(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) =>
    k in vars ? String(vars[k]) : `{${k}}`);
}

interface I18n {
  lang: Lang;
  /** Перевод по ключу. Незнакомый ключ возвращается как есть — заметно при отладке. */
  t: (key: string, vars?: Vars) => string;
  /** Число с правильной формой слова: plural(5, 'records') → «5 записей» */
  plural: (n: number, key: string) => string;
  dateLocale: Locale;
  numberLocale: string;
}

const I18nContext = createContext<I18n | null>(null);

export function useT(): I18n {
  const ctx = useContext(I18nContext);
  if (ctx) return ctx;
  // Без провайдера отдаём русский — компонент не должен падать
  return makeI18n('ru');
}

function makeI18n(lang: Lang): I18n {
  const dict = DICTS[lang];
  const rules = new Intl.PluralRules(NUMBER_LOCALE[lang]);

  const t = (key: string, vars?: Vars) => interpolate(dict[key] ?? key, vars);

  const plural = (n: number, key: string) => {
    // one / few / many / other — Intl сам выбирает нужную для языка
    const form = rules.select(n);
    const value = dict[`${key}.${form}`] ?? dict[`${key}.other`] ?? dict[`${key}.many`] ?? key;
    return interpolate(value, { n });
  };

  return { lang, t, plural, dateLocale: DATE_LOCALE[lang], numberLocale: NUMBER_LOCALE[lang] };
}

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  // Локаль чисел выставляем синхронно, до отрисовки детей: formatMoney вызывается
  // из десятков мест, и протаскивать локаль параметром в каждое — лишний шум
  setNumberLocale(NUMBER_LOCALE[lang]);
  const value = useMemo(() => makeI18n(lang), [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
